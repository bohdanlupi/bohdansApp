// Generates src/lib/heating/haka-data.ts from the digitised HAKA.GERODUR floor heating planning guide
// (Berechnungsvorlagen/Heizung/Fussbodenheizung/digitalisiert/haka-data.json – local only, gitignored; charts B1–B9,
// C and D were read from the vector paths of the PDF). Usage: node scripts/gen-haka-data.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const src = path.join(__dirname, "..", "Berechnungsvorlagen", "Heizung", "Fussbodenheizung", "digitalisiert", "haka-data.json");
const out = path.join(__dirname, "..", "src", "lib", "heating", "haka-data.ts");
const d = JSON.parse(fs.readFileSync(src, "utf8"));

const spacings = d.spacings_cm;
const byR = d.heatOutput.byRLambda;
const heatOutput = Object.fromEntries(
  Object.entries(byR).map(([r, chart]) => [r, Object.fromEntries(spacings.map((s) => [String(s), chart.curves[String(s)]]))]),
);
const data = {
  spacings,
  coveringResistances: Object.keys(byR).map(Number),
  heatOutput,
  surfaceLimits: d.surfaceTemperatureLimits.qMax_W_per_m2,
  downwardK: d.downwardLoss.K_W_per_m2K,
  insulationFactor: d.downwardLoss.insulationCorrection.f,
  pipes: d.pressureLoss.pipes.map((p) => ({ pipe: p.pipe.split(" ")[0], da: p.da_mm, di: p.di_mm, a: p.a, b: p.b })),
  coverings: d.coveringResistance.rows.map((r) => ({ name: r.covering, thickness: r.thickness_mm, r: r.R })),
};

const body = `// GENERATED by scripts/gen-haka-data.mjs from the digitised HAKA.GERODUR planning guide (Nass-System) – do not edit.
// heatOutput[Rλ][spacing cm] = polyline [Δθ K, q W/m²] (Tab. B1–B9); surfaceLimits = q at surface 24/26/28/30 °C;
// downwardK[spacing] = W/m²K for 20 mm insulation (Tab. C) with insulationFactor[mm]; pipes: m = a·R^b (Tab. D, 40 °C).

export const hakaData = ${JSON.stringify(data)} as const;
`;
fs.writeFileSync(out, body);
console.log("written", out, body.length);
