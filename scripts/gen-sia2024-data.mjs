// Generates src/lib/building/sia2024-data.ts from Berechnungsvorlagen/SIA/SIA_MB_2024_Alle_Nutzungen.pdf (gitignored):
// the 45 Raumnutzungen of SIA 2024:2021 with the standard values the building model and the later cooling load need.
// Each usage has two datasheet pages; the first carries the header «<name> <code>» and the values read here.
// Run: node scripts/gen-sia2024-data.mjs
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const PDF = path.join(root, "Berechnungsvorlagen/SIA/SIA_MB_2024_Alle_Nutzungen.pdf");
const OUT = path.join(root, "src/lib/building/sia2024-data.ts");

const pdfjs = await import(pathToFileURL(path.join(root, "node_modules/pdfjs-dist/legacy/build/pdf.mjs")).href);
const doc = await pdfjs.getDocument({ url: pathToFileURL(PDF).href, useSystemFonts: true, verbosity: 0 }).promise;

/** Lines of a page (items grouped by their y coordinate). */
async function pageLines(p) {
  const tc = await (await doc.getPage(p)).getTextContent();
  const lines = [];
  let last = null;
  for (const i of tc.items) {
    if (!("str" in i)) continue;
    const y = i.transform[5];
    if (last === null || Math.abs(y - last) > 4) lines.push("");
    lines[lines.length - 1] += i.str + " ";
    last = y;
  }
  return lines.map((l) => l.replace(/\s+/g, " ").trim()).filter(Boolean);
}

const num = (s) => {
  const v = Number(String(s).replace(",", "."));
  return Number.isFinite(v) ? v : null;
};
/** First number after the given label (standard value column). */
const valueAfter = (lines, label, unitPattern) => {
  const line = lines.find((l) => l.startsWith(label));
  if (!line) return null;
  const rest = line.slice(label.length);
  const m = new RegExp(`${unitPattern}\\s+(-?\\d+(?:[.,]\\d+)?)`).exec(rest);
  return m ? num(m[1]) : null;
};

const usages = [];
const seen = new Set();
for (let p = 1; p <= doc.numPages; p++) {
  const lines = await pageLines(p);
  if (lines[0] !== "SIA 2024 Raum-Datenblätter") continue;
  const head = /^(.*)\s(\d{1,2}\.\d{1,2})$/.exec(lines[1] ?? "");
  if (!head) continue;
  const code = head[2];
  if (seen.has(code)) continue; // second page of the usage
  seen.add(code);
  usages.push({
    code,
    name: head[1].trim(),
    thetaDesignCooling: valueAfter(lines, "Raumtemperatur-Auslegungswert Auslegung Kühlung", "°C"),
    thetaDesignHeating: valueAfter(lines, "Auslegung Heizung q i,des,H", "°C"),
    personArea: valueAfter(lines, "Personenfläche Nettogeschossfläche pro Person", "m 2"),
    personHeatCooling: valueAfter(lines, "Sensible Wärmeeintragsleistung Personen Auslegung Kühlung", "W/m 2"),
    deviceHeat: valueAfter(lines, "Wärmeeintragsleistung der Geräte", "W/m 2"),
    hoursPerDay: valueAfter(lines, "Nutzungsstunden pro Tag", "h"),
    daysPerYear: valueAfter(lines, "Nutzungstage pro Jahr", "d"),
  });
}
if (usages.length < 40) throw new Error(`only ${usages.length} usages found`);

const out = `// GENERATED by scripts/gen-sia2024-data.mjs – do not edit.
// Raumnutzungen of SIA 2024:2021 (Raum-Datenblätter, Standardwerte) for the room types of the building model and the
// later cooling load. Names are the German norm terms.

export type RoomUsage = {
  code: string;
  name: string;
  /** Design room temperatures [°C] for cooling and heating. */
  thetaDesignCooling: number | null;
  thetaDesignHeating: number | null;
  /** Nettogeschossfläche per person [m²/P]. */
  personArea: number | null;
  /** Sensible heat of persons at cooling design [W/m²] and of devices [W/m²]. */
  personHeatCooling: number | null;
  deviceHeat: number | null;
  hoursPerDay: number | null;
  daysPerYear: number | null;
};

export const roomUsages: readonly RoomUsage[] = ${JSON.stringify(usages, null, 2)};

export const roomUsageByCode = (code: string | null) => (code ? roomUsages.find((u) => u.code === code) ?? null : null);
`;
writeFileSync(OUT, out);
console.log(`wrote ${OUT}: ${usages.length} usages`);
await doc.destroy();
