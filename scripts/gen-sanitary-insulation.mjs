// Generates src/lib/sanitary/insulation-data.ts from the Meier Tobler IGH catalogue in the database: the pipe
// insulation shells of the Sanitär material list, per pipe diameter and thickness –
//   Mineralwolle: ROHHE r.Heat A Steinwolle Rohrschale Alu kaschiert («…Alu Kaschiert 28/30mm»)
//   PIR:          swisspor Kisodur PIR Alu Schalen, glatt («…PIR Alu Schalen 28x30 mm»; not «Grobkorn» / «Gitter»)
// Usage (needs .env): node --env-file=.env scripts/gen-sanitary-insulation.mjs

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { createClient } from "@supabase/supabase-js";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.join(root, "src", "lib", "sanitary", "insulation-data.ts");

const supabase = createClient(process.env.NEXT_PUBLIC_SUPABASE_URL, process.env.SUPABASE_SECRET_KEY, {
  auth: { persistSession: false },
  global: { headers: { "User-Agent": "lupi-cli/1.0" } },
});

const { data: catalog, error } = await supabase.from("catalogs").select("id").eq("source", "igh").ilike("name", "%meier tobler%").single();
if (error) throw error;

async function search(pattern) {
  const rows = [];
  for (let from = 0; ; from += 1000) {
    const { data, error: e } = await supabase
      .from("catalog_nodes")
      .select("article_number, short_text, unit")
      .eq("catalog_id", catalog.id)
      .eq("kind", "position")
      .ilike("search_text", pattern)
      .order("article_number")
      .range(from, from + 999);
    if (e) throw e;
    rows.push(...data);
    if (data.length < 1000) break;
  }
  return rows;
}

const shells = [];
for (const r of await search("%steinwolle rohrschale alu kaschiert%")) {
  const text = (r.short_text?.de ?? "").replace(/\s+/g, " ").trim();
  const m = /^ROHHE r\.Heat ® A Steinwolle Rohrschale Alu Kaschiert (\d+(?:\.\d+)?)\/(\d+)mm$/.exec(text);
  if (m) shells.push({ material: "mineralwool", number: r.article_number, text, od: Number(m[1]), mm: Number(m[2]), unit: r.unit ?? "m" });
}
for (const r of await search("%kisodur pir alu schalen%")) {
  const text = (r.short_text?.de ?? "").replace(/\s+/g, " ").trim();
  const m = /^swisspor Kisodur PIR Alu Schalen (\d+(?:\.\d+)?)x(\d+) mm$/.exec(text);
  if (m) shells.push({ material: "pir", number: r.article_number, text, od: Number(m[1]), mm: Number(m[2]), unit: r.unit ?? "m" });
}
shells.sort((a, b) => a.material.localeCompare(b.material) || a.mm - b.mm || a.od - b.od);

const banner = `// Generated by scripts/gen-sanitary-insulation.mjs from the IGH catalogue of Meier Tobler – do not edit.\n\n`;
const body =
  `/** Pipe insulation shell: material, Meier Tobler article, inner diameter (pipe OD) and thickness [mm]. */\n` +
  `export type InsulationShell = { material: "mineralwool" | "pir"; number: string; text: string; od: number; mm: number; unit: string };\n\n` +
  `export const insulationShells: InsulationShell[] = ${JSON.stringify(shells, null, 2)};\n`;
fs.writeFileSync(out, banner + body);
const count = (m) => shells.filter((s) => s.material === m).length;
console.log(`wrote ${path.relative(root, out)}: ${count("mineralwool")} Mineralwolle, ${count("pir")} PIR shells`);
